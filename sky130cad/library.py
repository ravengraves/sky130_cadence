def write_symbols(oa_dir, lef, env=None):
    """Symbol views (box symbols from the LEF pin list) for every cell of the OA library."""
    pins = lef_pins(lef)
    rows = '\n'.join('    list("%s" list(%s))' % (m, ' '.join('list("%s" "%s")' % (p, d) for p, d in pl))
                     for m, pl in sorted(pins.items()))
    open(os.path.join(oa_dir, 'symbols.il'), 'w').write(SYMBOLS % (rows, LIB))
    open(os.path.join(oa_dir, 'cds.lib'), 'a').write('DEFINE %s ./%s\n' % (LIB, LIB))
    toolenv.run(['virtuoso', '-nograph', '-replay', 'symbols.il', '-log', 'symbols.log'], oa_dir,
                os.path.join(oa_dir, 'symbols.out'), env, 3600)
    log = open(os.path.join(oa_dir, 'symbols.log')).read() if os.path.exists(os.path.join(oa_dir, 'symbols.log')) else ''
    m = re.findall(r'SKY130CAD_SYMBOLS (\d+)', log)
    return int(m[-1]) if m else 0, len(pins)


# ---------------------------------------------------------------- block LVS

def subckt_pins(cdl):
    pins = {}
    for line in open(cdl).read().split('\n'):
        tok = line.split()
        if tok and tok[0].lower() == '.subckt':
            pins[tok[1]] = tok[2:]
    return pins


def empty_subckts(cdl):
    """Library cells without devices (fillers, taps): physical only, left out of the LVS source."""
    empty, cur, n = set(), None, 0
    for line in open(cdl).read().split('\n'):
        tok = line.split()
        if not tok:
            continue
        if tok[0].lower() == '.subckt':
            cur, n = tok[1], 0
        elif tok[0].lower() == '.ends':
            if cur and n == 0:
                empty.add(cur)
            cur = None
        elif cur and tok[0][0] in 'mMdDrRcCxXqQ':
            n += 1
    return empty


def _strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def _net(n):
    n = n.strip()
    if n.startswith('\\'):
        n = n[1:].strip()
    return n


def verilog_to_cdl(netlist, lib_cdl, dst, top=None):
    """Structural Verilog (one or more modules) -> CDL. Buses are expanded bit by bit with
    names like a[3]; constants 1'b0/1'b1 become nets VGND_TIE/VPWR_TIE (reported)."""
    pins = subckt_pins(lib_cdl)
    empty = empty_subckts(lib_cdl)
    text = _strip_comments(open(netlist).read())
    out, warnings, nmods = ['*.SCALE MICRON', '.INCLUDE %s' % os.path.abspath(lib_cdl)], [], 0
    for m in re.finditer(r'\bmodule\s+(\\?\S+?)\s*\((.*?)\)\s*;(.*?)\bendmodule', text, re.S):
        name, body = _net(m.group(1)), m.group(3)
        ranges = {}
        for d in re.finditer(r'\b(input|output|inout|wire)\s+(?:\[(\d+):(\d+)\]\s*)?([^;]+);', body):
            for n in d.group(4).split(','):
                n = _net(n)
                if d.group(2):
                    ranges[n] = (int(d.group(2)), int(d.group(3)))
        ports = []
        for p in m.group(2).split(','):
            p = _net(p)
            if not p:
                continue
            if p in ranges:
                a, b = ranges[p]
                step = -1 if a >= b else 1
                ports += ['%s[%d]' % (p, i) for i in range(a, b + step, step)]
            else:
                ports.append(p)
        header = len(out)
        out.append('.SUBCKT %s %s' % (name, ' '.join(ports)))
        supplies = []
        assigns = re.findall(r'\bassign\s+([^=]+)=([^;]+);', body)
        for lhs, rhs in assigns:
            warnings.append('assign %s = %s (not converted)' % (lhs.strip(), rhs.strip()))
        k = 0
        for inst in re.finditer(r'(\\?[A-Za-z_][\w$]*)\s+(\\\S+|[A-Za-z_][\w$\[\]]*)\s*\((\s*\..*?)\)\s*;', body, re.S):
            cell, iname, conns = inst.group(1), _net(inst.group(2)), inst.group(3)
            if cell in ('input', 'output', 'inout', 'wire', 'assign', 'module'):
                continue
            pm = {}
            for c in re.finditer(r'\.(\w+)\s*\(\s*(.*?)\s*\)\s*(?=,|$)', conns, re.S):
                v = _net(c.group(2))
                if v in ("1'b0", "1'h0"):
                    v = 'VGND_TIE'
                elif v in ("1'b1", "1'h1"):
                    v = 'VPWR_TIE'
                pm[c.group(1)] = v
            if cell not in pins:
                warnings.append('instance %s of unknown cell %s' % (iname, cell))
                continue
            if cell in empty:          # filler / tap: no devices, nothing to compare
                continue
            nets = []
            for p in pins[cell]:
                v = pm.get(p, '')
                if p in ('VPWR', 'VGND', 'VPB', 'VNB') and v and v not in ports and v not in supplies:
                    supplies.append(v)
                if not v:
                    k += 1
                    v = 'UNCONNECTED_%s_%s' % (iname.replace('/', '_'), p)
                nets.append(v)
            out.append('X%s %s %s' % (iname, ' '.join(nets), cell))
        if supplies:
            # supply nets (vdd/gnd) are labeled pins in the layout: make them ports of the block
            out[header] = '.SUBCKT %s %s' % (name, ' '.join(ports + supplies))
        out.append('.ENDS')
        nmods += 1
    open(dst, 'w').write('\n'.join(out) + '\n')
    return nmods, warnings


def block_lvs(gds, top, netlist, lib_cdl, outdir, deck, env=None):
    os.makedirs(outdir, exist_ok=True)
    src = os.path.join(outdir, top + '.src.cdl')
    nmods, warnings = verilog_to_cdl(netlist, lib_cdl, src, top)
    flat = os.path.join(outdir, top + '.src_flat.cdl')
    # inline the library so the source is self-contained (Pegasus reads one file)
    text = open(src).read().replace('.INCLUDE %s\n' % os.path.abspath(lib_cdl), '')
    lib = '\n'.join(l for l in open(lib_cdl).read().split('\n') if not l.startswith('*'))
    open(flat, 'w').write('*.SCALE MICRON\n' + lib + '\n' + text.replace('*.SCALE MICRON\n', ''))
    res, summ = lvs.run(gds, top, flat, outdir, deck, env, extra=['-automatch'])
    return res, summ, warnings
