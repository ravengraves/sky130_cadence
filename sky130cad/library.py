"""Library-level views, as a foundry kit ships them (cf. GPDK045 gsclib045: cdl/, gds/,
oa22/, spectre/*_extracted), and full-chip LVS of placed-and-routed blocks.

  python3 sky130.py library        -> WORK/library/: sky130_fd_sc_hs.cdl, sky130_fd_sc_hs.gds,
                                      sky130_fd_sc_hs.v (functional simulation models, flat),
                                      oa/sky130_fd_sc_hs (Virtuoso layout views, if Virtuoso runs)
  python3 sky130.py lvs-block GDS TOP NETLIST.v [--deck cornell]

- CDL: every cell's .spice converted with lvs.spice_to_cdl (current device names, w/l in um).
- GDS: all 390 cell structures in one library file (no top cell), for strmin and viewers.
- Verilog: zero-delay functional models generated from the Liberty functions (flip-flops and
  latches with clear/preset, three-state outputs). The upstream models at the pinned commit do
  not compile: they reference u_vpwr_vgnd / u_df_p_no_pg-style primitives the repository does
  not ship, and some contain syntax errors (e.g. `wire C1 and0_out;` in a2111o).
- OA: `strmin` of the merged GDS into library sky130_fd_sc_hs attached to the sky130
  technology library (release/virtuoso/sky130).

Block LVS: the Innovus netlist (`saveNetlist -includePowerGround -includePhysicalInst`, so
decap and antenna-diode cells with their supply pins are present) is converted to CDL that
instantiates the library subcircuits by pin name; instances of device-free cells (fillers,
taps) are left out. Pegasus compares hierarchically with the cells as matching hcells.
"""
import glob
import os
import re

from . import cell_array, lvs, toolenv

LIB = 'sky130_fd_sc_hs'


def cells(fdsc):
    return sorted(os.path.basename(g)[:-4] for g in glob.glob(os.path.join(fdsc, 'cells', '*', LIB + '__*.gds')))


def write_cdl(fdsc, dst):
    parts, n = ['* %s cell netlists (from SkyWater .spice; w/l in um). Generated by sky130cad/library.py' % LIB,
                '*.SCALE MICRON'], 0
    tmp = dst + '.tmp'
    for c in cells(fdsc):
        src = glob.glob(os.path.join(fdsc, 'cells', '*', c + '.spice'))
        if not src:
            continue
        lvs.spice_to_cdl(src[0], tmp)
        body = [l for l in open(tmp).read().split('\n') if l and not l.startswith('*')]
        parts += body + ['']
        n += 1
    os.remove(tmp)
    open(dst, 'w').write('\n'.join(parts) + '\n')
    return n


def write_gds(fdsc, dst):
    """All cell structures in one GDS library (first copy of each structure name)."""
    units, seen, body = None, set(), []
    for c in cells(fdsc):
        u, structs = cell_array.read_lib(glob.glob(os.path.join(fdsc, 'cells', '*', c + '.gds'))[0])
        units = units or u
        for name, s in structs.items():
            if name not in seen:
                seen.add(name)
                body.append(s[0])   # BGNSTR .. ENDSTR bytes
    head = (cell_array.rec(0x00, 2, b'\x02\x58') + cell_array.rec(0x01, 2, b'\0' * 24) +
            cell_array.name_rec(0x02, LIB) + units)
    open(dst, 'wb').write(head + b''.join(body) + cell_array.rec(0x04, 0))
    return len(seen)


def lib_groups(text, keyword):
    """(argument, body) of every `keyword (arg) { ... }` group at any depth."""
    for m in re.finditer(r'\b%s\s*\(([^)]*)\)\s*\{' % keyword, text):
        depth, i = 1, m.end()
        while depth:
            c = text[i]
            depth += (c == '{') - (c == '}')
            i += 1
        yield m.group(1).strip().strip('"'), text[m.end():i - 1]


def v_expr(expr):
    """Liberty boolean expression -> Verilog (! ' + * ^ & | space-AND, 0/1)."""
    expr = expr.strip().strip('"')
    toks = re.findall(r"[A-Za-z_][A-Za-z_0-9]*|[01]|[()!~&|^+*']", expr)
    if re.sub(r'\s+', '', expr) != ''.join(toks):
        raise ValueError(expr)
    out = []
    for i, t in enumerate(toks):
        if t == "'":            # postfix complement: A' -> ~(A)
            prev = out.pop()
            out.append('~(%s)' % prev)
            continue
        if i and (re.fullmatch(r'\w+', toks[i - 1]) or toks[i - 1] in (')', "'")) and (
                re.fullmatch(r'\w+', t) or t in ('(', '!', '~')):
            out.append('&')
        out.append({'!': '~', '+': '|', '*': '&', '0': "1'b0", '1': "1'b1"}.get(t, t))
    return ' '.join(out)


def _attr(body, name):
    m = re.search(r'\b%s\s*:\s*("([^"]*)"|[^;]+);' % name, body)
    return (m.group(2) if m.group(2) is not None else m.group(1)).strip() if m else None


def _edge(expr):
    """'CLK' -> ('posedge', 'CLK'); '!CLK_N' -> ('negedge', 'CLK_N')."""
    e = expr.strip().strip('"').replace(' ', '')
    m = re.fullmatch(r'[!~]?(\w+)', e)
    if not m:
        raise ValueError('edge expression %s' % expr)
    return ('negedge' if e[0] in '!~' else 'posedge'), m.group(1)


def write_verilog(liberty, dst):
    """Zero-delay functional models generated from the Liberty cell functions (combinational
    functions, three-state enables, flip-flops and latches with clear/preset)."""
    text = open(liberty).read()
    out = ['// %s functional models (zero delay), generated by sky130cad/library.py from' % LIB,
           '// %s. Cells described by a statetable are black boxes.' % os.path.basename(liberty),
           '`timescale 1ns/1ps']
    n, black = 0, []
    for cell, body in lib_groups(text, 'cell'):
        for _, tc in lib_groups(body, 'test_cell'):     # scan cells repeat their pins here
            body = body.replace(tc, '')
        # internal pins (e.g. in clock gates) are not ports
        pins = [(p, b) for p, b in lib_groups(body, 'pin') if _attr(b, 'direction') in ('input', 'output', 'inout')]
        names = [p for p, _ in pins]
        out.append('module %s(%s);' % (cell, ', '.join(names)))
        for p, b in pins:
            out.append('  %s %s;' % ({'input': 'input', 'output': 'output', 'inout': 'inout'}[_attr(b, 'direction')], p))
        if 'statetable' in body:
            black.append(cell)
            out.append('  // statetable: not modelled')
            out.append('endmodule')
            continue
        for kind in ('ff', 'latch'):
            for state, g in lib_groups(body, kind):
                q, qn = [x.strip().strip('"') for x in state.split(',')]
                clear, preset = _attr(g, 'clear'), _attr(g, 'preset')
                out.append('  reg %s; wire %s = ~%s;' % (q, qn, q))
                if kind == 'ff':
                    ev = ['%s %s' % _edge(_attr(g, 'clocked_on'))]
                    if clear:
                        ev.append('%s %s' % _edge(clear))
                    if preset:
                        ev.append('%s %s' % _edge(preset))
                    stmt = '%s <= %s;' % (q, v_expr(_attr(g, 'next_state')))
                    if preset:
                        stmt = 'if (%s) %s <= 1\'b1; else %s' % (v_expr(preset), q, stmt)
                    if clear:
                        stmt = 'if (%s) %s <= 1\'b0; else %s' % (v_expr(clear), q, stmt)
                    out.append('  always @(%s) %s' % (' or '.join(ev), stmt))
                else:
                    stmt = 'if (%s) %s = %s;' % (v_expr(_attr(g, 'enable')), q, v_expr(_attr(g, 'data_in')))
                    if preset:
                        stmt = 'if (%s) %s = 1\'b1; else %s' % (v_expr(preset), q, stmt)
                    if clear:
                        stmt = 'if (%s) %s = 1\'b0; else %s' % (v_expr(clear), q, stmt)
                    out.append('  always @* %s' % stmt)
        for p, b in pins:
            f = _attr(b, 'function')
            if f:
                ts = _attr(b, 'three_state')
                if ts:
                    out.append("  assign %s = (%s) ? 1'bz : (%s);" % (p, v_expr(ts), v_expr(f)))
                else:
                    out.append('  assign %s = %s;' % (p, v_expr(f)))
        out.append('endmodule')
        n += 1
    open(dst, 'w').write('\n'.join(out) + '\n')
    return n, black


STRMIN_CDS = 'DEFINE sky130 %s\n'


def write_oa(gds, tech_lib, layer_map, out_dir, env=None):
    """strmin the merged GDS into OA library sky130_fd_sc_hs (attached to sky130)."""
    os.makedirs(out_dir, exist_ok=True)
    open(os.path.join(out_dir, 'cds.lib'), 'w').write(STRMIN_CDS % os.path.abspath(tech_lib))
    lib_dir = os.path.join(out_dir, LIB)
    import shutil
    shutil.rmtree(lib_dir, ignore_errors=True)     # strmin refuses a non-empty library folder
    rc = toolenv.run(['strmin', '-library', LIB, '-strmFile', os.path.abspath(gds), '-attachTechFileOfLib', 'sky130',
                      '-layerMap', os.path.abspath(layer_map), '-logFile', 'strmin.log', '-writeMode', 'overwrite'],
                     out_dir, os.path.join(out_dir, 'strmin.out'), env, 1800)
    views = len(glob.glob(os.path.join(lib_dir, '*', 'layout', 'layout.oa')))
    return rc, views


def lef_pins(lef):
    """{macro: [(pin, direction)]} from a cell LEF (DIRECTION INPUT/OUTPUT/INOUT; supplies inout)."""
    out, cur, pin = {}, None, None
    for line in open(lef):
        t = line.split()
        if t[:1] == ['MACRO']:
            cur = t[1]
            out[cur] = []
        elif t[:1] == ['PIN'] and cur:
            pin = [t[1], 'inputOutput']
            out[cur].append(pin)
        elif t[:1] == ['DIRECTION'] and pin is not None:
            pin[1] = {'INPUT': 'input', 'OUTPUT': 'output'}.get(t[1].rstrip(';'), 'inputOutput')
        elif t[:1] == ['END'] and len(t) > 1 and t[1] == (pin[0] if pin else None):
            pin = None
    return out


