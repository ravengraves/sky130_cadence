#!/usr/bin/env python3
"""Write Spectre-loadable SkyWater model files for digital cells (1.8 V transistors only).

  python3 sky130.py spectre-models      (MODELS_DIR = WORK/upstream/sky130_fd_pr/models)

Spectre cannot read the full `sky130.lib.spice`: high-voltage, resistor and bipolar model
files use Spectre `include` statements inside SPICE sections and `{}` expressions
(SFE-1802/841/874). Standard cells use only nfet_01v8(_lvt) and pfet_01v8(_hvt). For
each corner this keeps, from the library's own `.lib <corner>` section, only the include
lines for those four device folders, plus the scale option, LOD parameters and
`dlc_rotweak` parameters from `all.spice`. Output: OUT_DIR/sky130_digital_<corner>.spice with
every referenced file copied to OUT_DIR/fd_pr/ and included by a relative path, so the folder
can be moved or published as is.

The transistor files are written for ngspice: each subcircuit declares its parameters with
a `.param` line inside the subcircuit and uses `{expr}`. Spectre then rejects instance
parameters (SFE-1997 "Unknown parameter [l]"). Patched copies go to OUT_DIR/fd_pr/:
the `.param` defaults move onto the `.subckt` line and `{expr}` becomes `'expr'`.
The PDK files are not modified. Default corners: tt ss ff sf fs.
"""
import os
import re
import sys

DEVICES = ('nfet_01v8', 'nfet_01v8_lvt', 'pfet_01v8', 'pfet_01v8_hvt')


def lib_section(text, corner):
    m = re.search(r'^\.lib %s\s*$(.*?)^\.endl' % re.escape(corner), text, re.S | re.M)
    if not m:
        sys.exit('corner %s not found' % corner)
    return m.group(1)


def keep_include(line):
    m = re.match(r'\s*\.include\s+"([^"]+)"', line)
    if not m:
        return None
    path = m.group(1)
    folder = path.split('/cells/')[1].split('/')[0] if '/cells/' in path else None
    return path if folder in DEVICES else None


def all_spice_header(models, fd_pr_dir=None, done=None):
    """`.option scale`, parameters/lod.spice and the dlc_rotweak .param block of all.spice.
    With fd_pr_dir, included parameter files are copied there and referenced relatively."""
    out, in_param = [], False
    for line in open(os.path.join(models, 'all.spice')):
        s = line.strip()
        if s.startswith('.option'):
            out.append(s)
        elif s.startswith('.include') and 'parameters/' in s:
            src = os.path.join(models, s.split('"')[1])
            if fd_pr_dir is None:
                out.append('.include "%s"' % src)
            else:
                copy_patched(src, fd_pr_dir, done)
                out.append('.include "fd_pr/%s"' % os.path.basename(src))
        elif s == '.param':
            in_param = True
            out.append(s)
        elif in_param and s.startswith('+'):
            if 'rotweak' in s and ('__' not in s or any('__%s__' % d in s for d in DEVICES)):
                out.append(s)
        elif in_param:
            in_param = False
    return out


def patch_spice(text):
    """ngspice subckt `.param` defaults -> `.subckt` line parameters; {expr} -> 'expr'."""
    def move(m):
        params = re.sub(r'\s*=\s*', '=', m.group(2).strip())
        return '%s %s\n' % (m.group(1).rstrip(), params)
    text = re.sub(r'^(\.subckt[^\n]*)\n(?:\+\s*\n)*\.param\s+([^\n]*)\n', move, text, flags=re.M | re.I)
    return re.sub(r'\{([^{}]*)\}', r"'\1'", text)


def copy_patched(src, dst_dir, done):
    """Copy src (and the files it .includes) into dst_dir, patched; return the new path."""
    dst = os.path.join(dst_dir, os.path.basename(src))
    if dst in done:
        return dst
    done.add(dst)
    text = open(src).read()

    def inc(m):
        # Spectre resolves relative includes from the including file's folder, and every
        # copied file lands in dst_dir, so references are bare file names (relocatable).
        child = os.path.normpath(os.path.join(os.path.dirname(src), m.group(1)))
        return '.include "%s"' % os.path.basename(copy_patched(child, dst_dir, done))
    text = re.sub(r'^\.include\s+"([^"]+)"', inc, text, flags=re.M)
    open(dst, 'w').write(patch_spice(text))
    return dst


def main(models, out_dir, corners):
    text = open(os.path.join(models, 'sky130.lib.spice')).read()
    fd_pr = os.path.join(out_dir, 'fd_pr')
    os.makedirs(fd_pr, exist_ok=True)
    done = set()
    head = all_spice_header(models, fd_pr, done)
    for c in corners:
        lines = ['* SkyWater sky130 digital transistor subset (%s) for Spectre.' % ', '.join(DEVICES),
                 '* Generated by sky130cad/spectre_models.py from sky130_fd_pr models, .lib %s.' % c,
                 '* Includes are relative to this file (Spectre resolves them from here).',
                 'simulator lang=spice'] + head
        n = 0
        for line in lib_section(text, c).split('\n'):
            path = keep_include(line)
            if path:
                src = os.path.normpath(os.path.join(models, path))
                lines.append('.include "fd_pr/%s"' % os.path.basename(copy_patched(src, fd_pr, done)))
                n += 1
        out = os.path.join(out_dir, 'sky130_digital_%s.spice' % c)
        open(out, 'w').write('\n'.join(lines) + '\n')
        print('wrote %s (%d device includes)' % (out, n))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3:] or ['tt', 'ss', 'ff', 'sf', 'fs'])
