    # mos/: generated transistors (sky130cad/mosgen.py), GDS + CDL + Spectre subcircuit each
    os.makedirs(o('mos'), exist_ok=True)
    for dev, w_, l_, nf, tap, tie in mosgen.CHECK:
        name, S, Lb, prm = mosgen.generate(dev, w_, l_, nf, tap, tie)
        mosgen.write_gds(o('mos', name + '.gds'), [(name, S, Lb)])
        cdl, sp = mosgen.netlists(name, prm)
