HOME_PATH = re.compile(r'/(?:home|Users|tmp|scratch)/[^\s"\'<>]*')


def scrub_paths(out, work):
    """Replace absolute paths in text files: WORK -> $SKY130_WORK, others -> <path>/basename;
    the build machine's host name -> build-host. Raises if a home path is left anywhere (binary
    files included)."""
    import socket
    work = os.path.abspath(work)
    hosts = sorted({h for h in (socket.getfqdn(), socket.gethostname()) if h and h != 'localhost'},
                   key=len, reverse=True)
    n = 0
    for dp, _, fns in os.walk(out):
        for fn in fns:
            f = os.path.join(dp, fn)
            data = open(f, 'rb').read()
            if b'\0' in data[:8192]:
                if re.search(rb'/(?:home|Users)/', data):
                    raise SystemExit('binary file with a home path: %s' % f)
                continue
            text = data.decode('utf-8', 'replace')
            new = text.replace(work, '$SKY130_WORK')
            new = HOME_PATH.sub(lambda m: '<path>/' + m.group(0).rstrip('/').rsplit('/', 1)[-1], new)
            # tool report headers name the build machine ("Host ID <name>")
            new = re.sub(r'Host ID [^)\s]+', 'Host ID build-host', new)
            for h in hosts:
                new = new.replace(h, 'build-host')
            if new != text:
                open(f, 'w').write(new)
                n += 1
    return n


def build(work, out, repo_root, env=None, version=None):
    version = version or default_version()
    w = lambda *p: os.path.join(work, *p)
    o = lambda *p: os.path.join(out, *p)
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    up = w('upstream')
    # tech/
    # Liberty gzip-compressed (Genus/Innovus read .lib.gz; cadence/*.tcl pick .lib or .lib.gz)
    for f in sorted(glob.glob(w('tech', '*.lib'))):
        gzip_copy(f, o('tech', os.path.basename(f) + '.gz'))
    for f in sorted(glob.glob(w('tech', 'ccs', '*.lib'))):      # CCS-noise Liberty (`sky130.py ccs-libs`)
        gzip_copy(f, o('tech', 'ccs', os.path.basename(f) + '.gz'))
    for f in [w('tech', n) for n in (LIB + '.tlef', LIB + '_innovus.tlef', LIB + '_cells.lef', 'streamOut.map',
                                     'extraction.layermap')]:
        copy(f, o('tech', os.path.basename(f)))
    for f in sorted(glob.glob(w('tech', 'gds', '*.gds'))):
        copy(f, o('tech', 'gds', os.path.basename(f)))
    cds = os.path.join(up, 'sky130_cds')
    copy(os.path.join(cds, 'PEX', 'qrcTechFile'), o('tech', 'qrcTechFile'))
    copy(os.path.join(cds, 'PEX', 'sky130.ict'), o('tech', 'sky130.ict'))
    # cadence/ (relative to tech/)
    cadence_setup.write(o('tech'), o('cadence'))
    # pegasus/
    n = drc_deck.write(o('pegasus', 'sky130_full.pvl'))
    lvs_deck.write(o('pegasus', 'sky130_lvs.pvl'))
    antenna_deck.write(o('pegasus', 'sky130_antenna.pvl'))
    os.makedirs(o('pegasus', 'tests'), exist_ok=True)
    antenna_deck.write_tests(o('pegasus', 'tests', 'antenna_tests.gds'), o('pegasus', 'tests', 'antenna_tests_cases.tsv'))
    os.makedirs(o('pegasus', 'tests'), exist_ok=True)
    drc_tests.write(o('pegasus', 'tests', 'drc_tests.gds'), o('pegasus', 'tests', 'drc_tests_cases.tsv'))
    # spectre/
    spectre_models.main(os.path.join(up, 'sky130_fd_pr', 'models'), o('spectre', 'models'), ['tt', 'ss', 'ff', 'sf', 'fs'])
    nets = 0
    os.makedirs(o('spectre', 'netlists'), exist_ok=True)
    for f in sorted(glob.glob(os.path.join(up, LIB, 'cells', '*', LIB + '__*.spice'))):
        spectre_netlist.convert(f, o('spectre', 'netlists', os.path.basename(f)))
        nets += 1
    open(o('spectre', 'inverter_ss.scs'), 'w').write(SPECTRE_EXAMPLE)
    # characterization/
    for d in sorted(glob.glob(w('char', '*'))):
        for f in glob.glob(os.path.join(d, '*.lib')) + glob.glob(os.path.join(d, 'compare.txt')):
            copy(f, o('characterization', os.path.basename(d), os.path.basename(f)))
    # library/ (cf. gsclib045 cdl/, gds/, verilog/, oa22/): from `sky130.py library`
    for f in (LIB + '.cdl', LIB + '.gds', LIB + '.v'):
        if os.path.exists(w('library', f)):
            copy(w('library', f), o('library', f))
    oa = w('library', 'oa', LIB)
    if os.path.isdir(oa):
        shutil.copytree(oa, o('library', 'oa', LIB), symlinks=False)
        open(o('library', 'oa', 'cds.lib'), 'w').write(
            'DEFINE sky130 ../../virtuoso/sky130\nDEFINE %s ./%s\n' % (LIB, LIB))
    # spectre/extracted/ (cf. gsclib045 spectre/*_extracted): Quantus netlists of every cell
    nx = sorted(glob.glob(w('quantus', 'netlists', '*.spice')))
    for f in nx:
        copy(f, o('spectre', 'extracted', os.path.basename(f)))
    copy(os.path.join(repo_root, 'docs', 'gpdk045_comparison.md'), o('GPDK045_COMPARISON.md')) \
        if os.path.exists(os.path.join(repo_root, 'docs', 'gpdk045_comparison.md')) else None
    # quantus/
    os.makedirs(o('quantus'), exist_ok=True)
    open(o('quantus', 'layer_setup'), 'w').write(quantus.LAYER_SETUP)
    open(o('quantus', 'tech_cmd'), 'w').write(quantus.TECH_CMD)
    # abstract/
    os.makedirs(o('abstract'), exist_ok=True)
    if os.path.exists(w('abstract', 'fdsc_abstract.lef')):
        copy(w('abstract', 'fdsc_abstract.lef'), o('abstract', 'fdsc_abstract.lef'))
