def default_version():
    import datetime
    return datetime.date.today().strftime('%Y.%m.%d')


def package(rel, dist, name='sky130_fd_sc_hs_cadence'):
    """Write DIST/<name>-<VERSION>.tar.gz of the release folder (sorted members, fixed owner and
    mtime, so the same release gives the same archive) and its .sha256. Returns (archive, digest)."""
    import gzip
    import tarfile
    version = open(os.path.join(rel, 'VERSION')).readline().split()[-1]
    base = '%s-%s' % (name, version)
    os.makedirs(dist, exist_ok=True)
    archive = os.path.join(dist, base + '.tar.gz')
    paths = sorted(os.path.relpath(os.path.join(dp, fn), rel) for dp, _, fns in os.walk(rel) for fn in fns)

    def norm(ti):
        ti.uid = ti.gid = 0
        ti.uname = ti.gname = ''
        ti.mtime = 0
        ti.mode = 0o755 if ti.isdir() or ti.mode & 0o111 else 0o644
        return ti
    with open(archive, 'wb') as raw, gzip.GzipFile(base + '.tar', 'wb', 9, raw, mtime=0) as gz, \
            tarfile.open(fileobj=gz, mode='w', format=tarfile.PAX_FORMAT) as tar:
        dirs = sorted({os.path.dirname(x) for x in paths for _ in [0]} - {''})
        for d in sorted({os.path.join(*parts[:i]) for d in dirs for parts in [d.split(os.sep)]
                         for i in range(1, len(parts) + 1)}):
            tar.add(os.path.join(rel, d), arcname=os.path.join(base, d), recursive=False, filter=norm)
        for x in paths:
            tar.add(os.path.join(rel, x), arcname=os.path.join(base, x), recursive=False, filter=norm)
    digest = sha256(archive)
    with open(archive + '.sha256', 'w') as f:
        f.write('%s  %s\n' % (digest, os.path.basename(archive)))
    return archive, digest


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def gzip_copy(src, dst):
    import gzip
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(os.path.realpath(src), 'rb') as fi, gzip.GzipFile(dst, 'wb', compresslevel=9, mtime=0) as fo:
        shutil.copyfileobj(fi, fo, 1 << 20)


def copy(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(os.path.realpath(src), dst)


