def check(rel, rundir, env=None, jobs=4, smoke_run=True):
    """Use the release as published: checksums, DRC deck on its test layout, the Spectre
    example, the Virtuoso technology library and the Genus/Innovus/Pegasus example.
    Returns {check: (ok, detail)}."""
    import re
    from . import toolenv
    rel, rundir = os.path.abspath(rel), os.path.abspath(rundir)
    os.makedirs(rundir, exist_ok=True)
    res = {}
    bad = [l.split('  ', 1)[1] for l in open(os.path.join(rel, 'MANIFEST.sha256')).read().split('\n')
           if l and sha256(os.path.join(rel, l.split('  ', 1)[1])) != l.split('  ', 1)[0]]
    res['manifest'] = (not bad, '%d files differ' % len(bad) if bad else 'all checksums match')
    # DRC deck on the published test layout
    d = os.path.join(rundir, 'drc_tests')
    os.makedirs(d, exist_ok=True)
    toolenv.run(['pegasus', '-drc', '-dp', str(jobs), '-gds', os.path.join(rel, 'pegasus', 'tests', 'drc_tests.gds'),
                 '-top_cell', 'drc_tests', os.path.join(rel, 'pegasus', 'sky130_full.pvl')], d,
                os.path.join(d, 'peg.out'), env, 1800)
    rpt = os.path.join(d, 'sky130_full.drc_errors.ascii')
    nbad = drc_tests.check(os.path.join(rel, 'pegasus', 'tests', 'drc_tests_cases.tsv'), rpt) if os.path.exists(rpt) else -1
    res['drc_tests'] = (nbad == 0, 'test cases wrong: %d' % nbad if nbad >= 0 else 'pegasus failed')
    # antenna deck on its published test layout
    d = os.path.join(rundir, 'antenna')
    os.makedirs(d, exist_ok=True)
    toolenv.run(['pegasus', '-drc', '-dp', str(jobs), '-gds', os.path.join(rel, 'pegasus', 'tests', 'antenna_tests.gds'),
                 '-top_cell', 'antenna_tests', os.path.join(rel, 'pegasus', 'sky130_antenna.pvl')], d,
                os.path.join(d, 'peg.out'), env, 900)
    rpt = os.path.join(d, 'sky130_antenna.drc_errors.ascii')
    nbad = antenna_deck.check(os.path.join(rel, 'pegasus', 'tests', 'antenna_tests_cases.tsv'), rpt) \
        if os.path.exists(rpt) else -1
    res['antenna_tests'] = (nbad == 0, 'test cases wrong: %d' % nbad if nbad >= 0 else 'pegasus failed')
    # Spectre example (includes resolved relative to the published files)
    d = os.path.join(rundir, 'spectre')
    os.makedirs(d, exist_ok=True)
    toolenv.run(['spectre', '-64', os.path.join(rel, 'spectre', 'inverter_ss.scs'), '=log', 'inv.log', '-raw', 'inv.raw'],
                d, os.path.join(d, 'spectre.out'), env, 600)
    log = open(os.path.join(d, 'inv.log')).read() if os.path.exists(os.path.join(d, 'inv.log')) else ''
    mf = os.path.join(d, 'inverter_ss.measure')   # .meas results (named after the netlist)
    meas = dict(re.findall(r'(tpd_\w+)\s*=\s*(\S+)', open(mf).read())) if os.path.exists(mf) else {}
    res['spectre'] = (len(meas) == 2 and 'completes with 0 errors' in log,
                      ', '.join('%s=%s' % kv for kv in sorted(meas.items())) or 'no measurements')
    # Virtuoso technology library
    d = os.path.join(rundir, 'virtuoso')
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, 'cds.lib'), 'w').write('DEFINE sky130 %s\n' % os.path.join(rel, 'virtuoso', 'sky130'))
    open(os.path.join(d, 'check.il'), 'w').write(VIRTUOSO_CHECK)
    toolenv.run(['virtuoso', '-nograph', '-replay', 'check.il', '-log', 'check.log'], d, os.path.join(d, 'v.out'), env, 600)
    vlog = open(os.path.join(d, 'check.log')).read() if os.path.exists(os.path.join(d, 'check.log')) else ''
    m = re.findall(r'SKY130CAD_TECH layers=(\d+) vias=(\d+)', vlog)
    m = [x for x in m if x != ('%d', '%d')]
    res['virtuoso_tech'] = (bool(m) and int(m[-1][0]) > 0, 'layers=%s vias=%s' % m[-1] if m else 'tech library not opened')
    # LVS deck on published cells and generated transistors
    d = os.path.join(rundir, 'lvs')
    deck = os.path.join(rel, 'pegasus', 'sky130_lvs.pvl')
    jobs_ = []
    for c in ('inv_1', 'nand2_1', 'mux2_1', 'dfxtp_1', 'conb_1', 'decap_4', 'xor3_1'):   # xor3_1: patched
        name = 'sky130_fd_sc_hs__' + c
        out = os.path.join(d, name)
        os.makedirs(out, exist_ok=True)
        lvs.spice_to_cdl(os.path.join(rel, 'spectre', 'netlists', name + '.spice'), os.path.join(out, 'src.cdl'))
        jobs_.append((os.path.join(rel, 'tech', 'gds', name + '.gds'), name, os.path.join(out, 'src.cdl'), out))
    for g in sorted(glob.glob(os.path.join(rel, 'mos', '*.gds'))):
        name = os.path.basename(g)[:-4]
        if not name.endswith('_notap'):
            jobs_.append((g, name, g[:-4] + '.cdl', os.path.join(d, name)))
    got = [(j[1], lvs.run(j[0], j[1], j[2], j[3], deck, env)[0]) for j in jobs_]
    bad = [n for n, r in got if r != 'MATCH']
    res['lvs'] = (not bad, '%d/%d MATCH%s' % (len(got) - len(bad), len(got), (': not ' + ', '.join(bad)) if bad else ''))
    # OSU second library as published: abutted/mirrored-row DRC and LVS of every cell
    od = os.path.join(rel, 'osu18t_hs')
    if os.path.isdir(od):
        from . import osu as osu_mod
        r, lv, _ = osu_mod.check(rundir, od, os.path.join(rel, 'pegasus', 'sky130_full.pvl'),
                                 os.path.join(rel, 'pegasus', 'sky130_lvs.pvl'), env, jobs,
                                 gds_dir=os.path.join(od, 'gds'), tag='osu')
        abut = sum(sum(c.values()) for c in (r.get('abut') or {}).values()) if r.get('abut') is not None else -1
        m = sum(1 for v, _ in lv.values() if v == 'MATCH')
        bad = sorted(c.replace('sky130_osu_sc_18T_hs__', '') for c, (v, _) in lv.items() if v not in ('MATCH', 'NO NETLIST'))
        res['osu'] = (abut == 0 and set(bad) <= {'dlat_1', 'dlat_l'},
                      'abutted-row DRC %d, LVS %d MATCH%s' % (abut, m, (' (not: %s)' % ', '.join(bad)) if bad else ''))
    # Genus -> Innovus -> Pegasus example
    if smoke_run:
        r = smoke.run(rundir, env, cadence_dir=os.path.join(rel, 'cadence'),
                      deck=os.path.join(rel, 'pegasus', 'sky130_full.pvl'),
                      example=os.path.join(rel, 'examples', 'smoke'), rundir=os.path.join(rundir, 'smoke'),
                      lvs_deck=os.path.join(rel, 'pegasus', 'sky130_lvs.pvl'),
                      lib_cdl=os.path.join(rel, 'library', LIB + '.cdl'))
        ok = bool(r.get('innovus') and r.get('innovus_drc') and r.get('connectivity')
                  and not r.get('empty_structures') and r.get('pegasus_results') == 0 and r.get('lvs') == 'MATCH')
        res['smoke'] = (ok, ', '.join('%s=%s' % kv for kv in r.items()))
    return res
