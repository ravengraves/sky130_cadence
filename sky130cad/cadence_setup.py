"""Write Genus/Innovus setup files for sky130_fd_sc_hs into WORK/cadence.

  python3 sky130.py cadence-setup

- genus_fdsc.tcl    fdsc_read_libs CORNER, fdsc_dont_use
- innovus_fdsc.tcl  fdsc_* procs: LEF list, power connection (VPWR/VPB -> vdd, VGND/VNB -> gnd),
                    routing layers (li1 is LEF routing layer 1, so met1..met5 = 2..6),
                    floorplan with site `unit`, rings/stripes, well taps every 13 um, sroute,
                    CTS clkbuf/clkinv cells, tie cell conb_1, antenna diode diode_2, fillers,
                    don't-use list, streamOut with the generated map and cell GDS merge
- mmmc_fdsc.tcl     SS 150 C, SS -40 C and TT 25 C setup and FF -40 C hold views; QRC tech file.
- mmmc_fdsc_genus.tcl  the same views for Genus read_mmmc (common-UI syntax).
                    Before sourcing, set `fdsc_sdc` to the SDC path.
All three find the tech folder relative to their own location.

The settings are the ones the sky130_fd_sc_hs place-and-route runs used with Innovus 20.16.
Lessons from those runs, encoded here:
- full adders `*__fah*` are don't-use: four fah_2/fahcin_1 instances could not be legalized
  (IMPSP-2021);
- post-route: OCV analysis mode and QRC extraction with the explicit layer map
  (`fdsc_post_route_settings`);
- optDesign useful skew is off after ccopt: with it on, post-CTS setup optimization chained
  ~7 ns of FE_USKC clock buffers onto output registers (`fdsc_post_cts_settings`).
"""
import os

LIB = 'sky130_fd_sc_hs'
DONT_USE = ['*__dlx*', '*__dlr*', '*__dlclkp*', '*__sdl*', '*__sdf*', '*__sed*', '*__einv*', '*__ebuf*',
            '*__probe*', '*__lpflow*', '*__dfr*', '*__dfs*', '*__dfbb*', '*__clkdly*', '*__dlymetal*',
            '*__macro*', '*__fah*', '*__tap*', '*__fill*', '*__decap*', '*__diode*']
# xor3_1 is usable again: its pin B was unreachable under an internal met1 strap (NanoRoute shorted
# to it on 15 of 28 instances); `convert` applies the layout fix in sky130cad/cellfix.py.
# Innovus: keep the hold-delay cells (dlygate4sd*) usable; physical cells are placed explicitly.
DONT_USE_INNOVUS = [p for p in DONT_USE if p not in ('*__tap*', '*__fill*', '*__decap*', '*__diode*')]


def genus_tcl(tech):
    return '''# Generated by sky130cad/cadence_setup.py
set fdsc_tech [file normalize [file join [file dirname [file normalize [info script]]] {%(tech)s}]]
set fdsc_lib %(lib)s
# Liberty file of a corner: .lib or gzip-compressed .lib.gz (Genus and Innovus read both)
proc fdsc_liberty {corner} {
    foreach ext {.lib .lib.gz} {
        set f [file join $::fdsc_tech %(lib)s__${corner}$ext]
        if {[file exists $f]} { return $f }
    }
    error "no Liberty for corner $corner in $::fdsc_tech"
}
proc fdsc_read_libs {{corner ss_150C_1v60}} {
    read_libs [fdsc_liberty $corner]
}
# Base-name patterns; latches, scan/async flops, tristates, delay and physical cells, fah*.
proc fdsc_dont_use {} {
    foreach pattern {%(du)s} {
        foreach c [get_db lib_cells */$pattern] { set_db $c .dont_use true }
    }
}
''' % {'tech': tech, 'lib': LIB, 'du': ' '.join(DONT_USE)}


def innovus_tcl(tech):
    L = LIB
    return '''# Generated by sky130cad/cadence_setup.py (settings validated with Innovus 20.16)
set fdsc_tech [file normalize [file join [file dirname [file normalize [info script]]] {%(tech)s}]]
set fdsc_init_lef_file [list [file join $fdsc_tech %(L)s_innovus.tlef] [file join $fdsc_tech %(L)s_cells.lef]]

proc fdsc_dont_use {} {
    foreach pattern {%(du)s} {
        if {[llength [dbGet -e head.libCells.name $pattern]]} { setDontUse $pattern true }
    }
}
proc fdsc_connect_power {{pwr vdd} {gnd gnd}} {
    foreach pin {VPWR VPB} { globalNetConnect $pwr -type pgpin -pin $pin -all }
    foreach pin {VGND VNB} { globalNetConnect $gnd -type pgpin -pin $pin -all }
    globalNetConnect $pwr -type tiehi -all
    globalNetConnect $gnd -type tielo -all
}
# li1 is LEF routing layer 1; route on met1 (2) .. met5 (6).
proc fdsc_route_settings {} {
    setDesignMode -process 130 -topRoutingLayer 6 -bottomRoutingLayer 2
    setNanoRouteMode -routeTopRoutingLayer 6 -routeBottomRoutingLayer 2
    setPlaceMode -place_detail_preroute_as_obs {5 6}
}
proc fdsc_floorplan {{util 0.50} {margin 16}} {
    floorPlan -site unit -r 1.0 $util $margin $margin $margin $margin
}
proc fdsc_power_grid {{pwr vdd} {gnd gnd}} {
    addRing -nets [list $pwr $gnd] -type core_rings -follow core \\
        -layer {top met5 bottom met5 left met4 right met4} \\
        -width 2.0 -spacing 1.6 -offset 2.0 -center 1
    addStripe -nets [list $pwr $gnd] -layer met4 -direction vertical -width 2.0 \\
        -spacing 2.0 -set_to_set_distance 100 -start_from left -start_offset 25
}
proc fdsc_welltaps {} {
    addWellTap -cell %(L)s__tapvpwrvgnd_1 -cellInterval 13 -prefix WELLTAP
}
proc fdsc_sroute {{pwr vdd} {gnd gnd}} {
    sroute -connect {corePin floatingStripe} -nets [list $pwr $gnd] -allowJogging 1 \\
        -allowLayerChange 1 -layerChangeRange {met1 met5} \\
        -targetViaLayerRange {met1 met5} -crossoverViaLayerRange {met1 met5}
}
proc fdsc_ties {} {
    setTieHiLoMode -maxFanout 8 -maxDistance 40
    addTieHiLo -cell %(L)s__conb_1 -prefix TIE
}
proc fdsc_cts_settings {} {
    set_ccopt_property buffer_cells {%(clkbuf)s}
    set_ccopt_property inverter_cells {%(clkinv)s}
    set_ccopt_property target_max_trans 0.20   ;# SS -40 C needs >= 0.177 ns (IMPCCOPT-1013)
    set_ccopt_property useful_skew_max_delta 0.75
}
# After ccopt_design: optDesign's own useful skew inserted long FE_USKC clock-buffer chains.
proc fdsc_post_cts_settings {} {
    setOptMode -usefulSkew false
}
# Before post-route optimization: SI-aware optDesign needs OCV analysis (IMPOPT-6080), and
# extraction uses the explicit LEF-to-QRC layer map when a QRC tech file is present.
proc fdsc_post_route_settings {} {
    if {[file exists [file join $::fdsc_tech qrcTechFile]]} {
        setExtractRCMode -engine postRoute -effortLevel high -lefTechFileMap [file join $::fdsc_tech extraction.layermap]
    } else {
        setExtractRCMode -engine postRoute
    }
    setAnalysisMode -analysisType onChipVariation -cppr both
}
proc fdsc_antenna {} {
    setNanoRouteMode -drouteFixAntenna true -routeInsertAntennaDiode true \\
        -routeAntennaCellName %(L)s__diode_2
}
proc fdsc_fillers {} {
    addFiller -cell {%(fill)s} -prefix FILL
}
proc fdsc_stream_out {gds top} {
    streamOut $gds -mapFile [file join $::fdsc_tech streamOut.map] -libName $top -structureName $top \\
        -units 1000 -mode ALL -merge [glob [file join $::fdsc_tech gds *.gds]]
}
''' % {'tech': tech, 'L': L, 'du': ' '.join(DONT_USE_INNOVUS),
       'clkbuf': ' '.join('%s__clkbuf_%d' % (L, s) for s in (2, 4, 8, 16)),
       'clkinv': ' '.join('%s__clkinv_%d' % (L, s) for s in (2, 4, 8, 16)),
       'fill': ' '.join('%s__fill_%d' % (L, s) for s in (8, 4, 2, 1))}


def mmmc_tcl(tech):
    L = LIB
    return '''# Generated by sky130cad/cadence_setup.py. Set fdsc_sdc before sourcing this file.
set fdsc_tech [file normalize [file join [file dirname [file normalize [info script]]] {%(tech)s}]]
# Liberty file of a corner: .lib or gzip-compressed .lib.gz (Genus and Innovus read both)
proc fdsc_liberty {corner} {
    foreach ext {.lib .lib.gz} {
        set f [file join $::fdsc_tech %(L)s__${corner}$ext]
        if {[file exists $f]} { return $f }
    }
    error "no Liberty for corner $corner in $::fdsc_tech"
}
set qrc [file join $fdsc_tech qrcTechFile]
create_library_set -name fdsc_slow -timing [list [fdsc_liberty ss_150C_1v60]]
create_library_set -name fdsc_cold -timing [list [fdsc_liberty ss_n40C_1v60_ccsnoise]]
create_library_set -name fdsc_typ -timing [list [fdsc_liberty tt_025C_1v80_ccsnoise]]
create_library_set -name fdsc_fast -timing [list [fdsc_liberty ff_n40C_1v95_ccsnoise]]
foreach {name temp} {fdsc_rc_slow 150 fdsc_rc_cold -40 fdsc_rc_typ 25 fdsc_rc_fast -40} {
    if {[file exists $qrc]} {
        create_rc_corner -name $name -T $temp -qx_tech_file $qrc
    } else {
        create_rc_corner -name $name -T $temp
    }
}
create_delay_corner -name fdsc_slow_corner -library_set fdsc_slow -rc_corner fdsc_rc_slow
create_delay_corner -name fdsc_cold_corner -library_set fdsc_cold -rc_corner fdsc_rc_cold
create_delay_corner -name fdsc_typ_corner -library_set fdsc_typ -rc_corner fdsc_rc_typ
create_delay_corner -name fdsc_fast_corner -library_set fdsc_fast -rc_corner fdsc_rc_fast
create_constraint_mode -name functional -sdc_files [list $fdsc_sdc]
create_analysis_view -name fdsc_slow_view -constraint_mode functional -delay_corner fdsc_slow_corner
create_analysis_view -name fdsc_cold_view -constraint_mode functional -delay_corner fdsc_cold_corner
create_analysis_view -name fdsc_typ_view -constraint_mode functional -delay_corner fdsc_typ_corner
create_analysis_view -name fdsc_fast_view -constraint_mode functional -delay_corner fdsc_fast_corner
# fd_sc_hs is slower at SS -40 C than at SS 150 C (temperature inversion): check both
set_analysis_view -setup {fdsc_slow_view fdsc_cold_view fdsc_typ_view} -hold {fdsc_fast_view}
''' % {'tech': tech, 'L': L}


def mmmc_genus_tcl(tech):
    """The same views in Genus's common-UI MMMC syntax (timing conditions, -qrc_tech)."""
    L = LIB
    return '''# Generated by sky130cad/cadence_setup.py (Genus read_mmmc). Set fdsc_sdc before reading.
if {![info exists fdsc_tech]} {
    set fdsc_tech [file normalize [file join [file dirname [file normalize [info script]]] {%(tech)s}]]
}
# Liberty file of a corner: .lib or gzip-compressed .lib.gz (Genus and Innovus read both)
proc fdsc_liberty {corner} {
    foreach ext {.lib .lib.gz} {
        set f [file join $::fdsc_tech %(L)s__${corner}$ext]
        if {[file exists $f]} { return $f }
    }
    error "no Liberty for corner $corner in $::fdsc_tech"
}
set qrc [file join $fdsc_tech qrcTechFile]
foreach {set corner} {fdsc_slow ss_150C_1v60 fdsc_cold ss_n40C_1v60_ccsnoise fdsc_typ tt_025C_1v80_ccsnoise
                      fdsc_fast ff_n40C_1v95_ccsnoise} {
    create_library_set -name $set -timing [list [fdsc_liberty $corner]]
    create_timing_condition -name ${set}_tc -library_sets $set
}
foreach {name temp} {fdsc_rc_slow 150 fdsc_rc_cold -40 fdsc_rc_typ 25 fdsc_rc_fast -40} {
    if {[file exists $qrc]} {
        create_rc_corner -name $name -temperature $temp -qrc_tech $qrc
    } else {
        create_rc_corner -name $name -temperature $temp
    }
}
foreach c {slow cold typ fast} {
    create_delay_corner -name fdsc_${c}_corner -timing_condition fdsc_${c}_tc -rc_corner fdsc_rc_$c
}
create_constraint_mode -name functional -sdc_files [list $fdsc_sdc]
foreach c {slow cold typ fast} {
    create_analysis_view -name fdsc_${c}_view -constraint_mode functional -delay_corner fdsc_${c}_corner
}
set_analysis_view -setup {fdsc_slow_view fdsc_cold_view fdsc_typ_view} -hold {fdsc_fast_view}
''' % {'tech': tech, 'L': L}


def write(tech, out):
    """The Tcl files locate the tech folder relative to themselves ([info script]), so a
    cadence/ + tech/ pair can be moved or published as is."""
    os.makedirs(out, exist_ok=True)
    tech = os.path.relpath(os.path.abspath(tech), os.path.abspath(out))
    files = {'genus_fdsc.tcl': genus_tcl(tech), 'innovus_fdsc.tcl': innovus_tcl(tech), 'mmmc_fdsc.tcl': mmmc_tcl(tech),
             'mmmc_fdsc_genus.tcl': mmmc_genus_tcl(tech)}
    for name, text in files.items():
        open(os.path.join(out, name), 'w').write(text)
    return [os.path.join(out, n) for n in files]
